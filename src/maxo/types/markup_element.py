from maxo.enums.markup_element_type import MarkupElementType
from maxo.types.base import MaxoType


class MarkupElement(MaxoType):
    """
    Args:
        from_: Индекс начала элемента разметки в тексте. Нумерация с нуля
        length: Длина элемента разметки в символах
        type: Тип элемента разметки. Может быть **жирный**,  _курсив_, ~зачеркнутый~, подчеркнутый, `моноширинный`, выделенный, цитата, заголовок, ссылка или упоминание пользователя
            **Обратите внимание**: в тексте комментариев не поддерживаются гиперссылки и упоминания пользователей
    """

    from_: int
    """Индекс начала элемента разметки в тексте. Нумерация с нуля"""
    length: int
    """Длина элемента разметки в символах"""
    type: MarkupElementType
    """
    Тип элемента разметки. Может быть **жирный**,  _курсив_, ~зачеркнутый~, подчеркнутый, `моноширинный`, выделенный, цитата, заголовок, ссылка или упоминание пользователя

    **Обратите внимание**: в тексте комментариев не поддерживаются гиперссылки и упоминания пользователей
    """

    @property
    def offset(self) -> int:
        # Подражание aiogram
        return self.from_
